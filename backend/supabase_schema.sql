create table if not exists public.users (
  id text primary key,
  email text null,
  plan text not null default 'free',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.usage_logs (
  id bigint generated by default as identity primary key,
  user_id text not null references public.users(id) on delete cascade,
  analysis_type text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.subscriptions (
  id bigint generated by default as identity primary key,
  user_id text not null references public.users(id) on delete cascade,
  plan text not null,
  status text not null default 'inactive',
  current_period_start timestamptz null,
  current_period_end timestamptz null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.analysis_logs (
  id bigint generated by default as identity primary key,
  user_id text not null references public.users(id) on delete cascade,
  analysis_type text not null,
  input_image_hash text null,
  result_json jsonb not null,
  model_name text null,
  prompt_version text null,
  analysis_mode text null,
  cache_key text null,
  created_at timestamptz not null default now()
);

alter table public.analysis_logs
  add column if not exists prompt_version text null;

alter table public.analysis_logs
  add column if not exists analysis_mode text null;

alter table public.analysis_logs
  add column if not exists cache_key text null;

create table if not exists public.feedback_logs (
  id bigint generated by default as identity primary key,
  user_id text not null references public.users(id) on delete cascade,
  analysis_id bigint not null references public.analysis_logs(id) on delete cascade,
  rating integer null check (rating between 1 and 5),
  correct_signal text null,
  correct_pattern text null,
  comment text null,
  created_at timestamptz not null default now()
);

create index if not exists idx_usage_logs_user_id_created_at
  on public.usage_logs (user_id, created_at desc);

create index if not exists idx_subscriptions_user_id
  on public.subscriptions (user_id);

create index if not exists idx_analysis_logs_user_id_created_at
  on public.analysis_logs (user_id, created_at desc);

create index if not exists idx_analysis_logs_cache_key
  on public.analysis_logs (cache_key);

create index if not exists idx_analysis_logs_user_cache_key
  on public.analysis_logs (user_id, cache_key);

create index if not exists idx_feedback_logs_user_id_analysis_id
  on public.feedback_logs (user_id, analysis_id);
