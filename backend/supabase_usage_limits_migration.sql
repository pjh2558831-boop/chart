-- Chart Vision AI usage/profile migration
-- IMPORTANT: Run this once in Supabase Dashboard -> SQL Editor.
-- Keeping this SQL file in the repository does not apply it to Supabase.
-- This migration is additive and safe for existing data.

begin;

-- 1. profiles: Supabase Auth user profile and plan source of truth.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  plan text not null default 'free',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.profiles
  add column if not exists email text;

alter table public.profiles
  add column if not exists plan text default 'free';

alter table public.profiles
  add column if not exists created_at timestamptz default now();

alter table public.profiles
  add column if not exists updated_at timestamptz default now();

update public.profiles
set plan = 'free'
where plan is null;

alter table public.profiles
  alter column plan set default 'free';

alter table public.profiles
  alter column plan set not null;

-- 2. usage_logs: permanent usage limit source for guest/user analysis.
create table if not exists public.usage_logs (
  id bigint generated by default as identity primary key,
  user_id text null,
  guest_id text null,
  analysis_type text,
  action text not null default 'analysis_success',
  plan_snapshot text not null default 'free',
  created_at timestamptz not null default now()
);

alter table public.usage_logs
  add column if not exists user_id text null;

alter table public.usage_logs
  alter column user_id drop not null;

alter table public.usage_logs
  add column if not exists guest_id text null;

alter table public.usage_logs
  add column if not exists action text default 'analysis_success';

alter table public.usage_logs
  add column if not exists plan_snapshot text default 'free';

alter table public.usage_logs
  add column if not exists analysis_type text;

alter table public.usage_logs
  add column if not exists created_at timestamptz default now();

alter table public.usage_logs
  alter column created_at set default now();

update public.usage_logs
set action = 'analysis_success'
where action is null;

update public.usage_logs
set plan_snapshot = 'free'
where plan_snapshot is null;

alter table public.usage_logs
  alter column action set default 'analysis_success';

alter table public.usage_logs
  alter column action set not null;

alter table public.usage_logs
  alter column plan_snapshot set default 'free';

alter table public.usage_logs
  alter column plan_snapshot set not null;

-- 3. analysis_logs: analysis result history and cache metadata.
create table if not exists public.analysis_logs (
  id bigint generated by default as identity primary key,
  user_id text null,
  guest_id text null,
  analysis_type text,
  input_image_hash text,
  result_json jsonb,
  model_name text,
  prompt_version text,
  analysis_mode text,
  cache_key text,
  created_at timestamptz not null default now()
);

alter table public.analysis_logs
  add column if not exists user_id text null;

alter table public.analysis_logs
  alter column user_id drop not null;

alter table public.analysis_logs
  add column if not exists guest_id text null;

alter table public.analysis_logs
  add column if not exists action text;

alter table public.analysis_logs
  add column if not exists plan_snapshot text;

alter table public.analysis_logs
  add column if not exists analysis_type text;

alter table public.analysis_logs
  add column if not exists input_image_hash text;

alter table public.analysis_logs
  add column if not exists result_json jsonb;

alter table public.analysis_logs
  add column if not exists model_name text;

alter table public.analysis_logs
  add column if not exists prompt_version text;

alter table public.analysis_logs
  add column if not exists analysis_mode text;

alter table public.analysis_logs
  add column if not exists cache_key text;

alter table public.analysis_logs
  add column if not exists created_at timestamptz default now();

alter table public.analysis_logs
  alter column created_at set default now();

-- 4. Indexes for fast usage checks, history lookup, and cache lookup.
create index if not exists idx_profiles_plan
  on public.profiles (plan);

create index if not exists idx_usage_logs_user_created_at
  on public.usage_logs (user_id, created_at desc);

create index if not exists idx_usage_logs_guest_created_at
  on public.usage_logs (guest_id, created_at desc);

create index if not exists idx_usage_logs_user_action_created_at
  on public.usage_logs (user_id, action, created_at desc);

create index if not exists idx_usage_logs_guest_action_created_at
  on public.usage_logs (guest_id, action, created_at desc);

create index if not exists idx_analysis_logs_user_created_at
  on public.analysis_logs (user_id, created_at desc);

create index if not exists idx_analysis_logs_guest_created_at
  on public.analysis_logs (guest_id, created_at desc);

create index if not exists idx_analysis_logs_cache_key
  on public.analysis_logs (cache_key);

create index if not exists idx_analysis_logs_user_cache_key
  on public.analysis_logs (user_id, cache_key);

create index if not exists idx_analysis_logs_guest_cache_key
  on public.analysis_logs (guest_id, cache_key);

commit;

-- Optional verification query.
-- Run after the migration to confirm required columns exist.
select
  table_name,
  column_name,
  data_type,
  is_nullable,
  column_default
from information_schema.columns
where table_schema = 'public'
  and table_name in ('profiles', 'usage_logs', 'analysis_logs')
  and column_name in (
    'id',
    'email',
    'plan',
    'user_id',
    'guest_id',
    'action',
    'analysis_type',
    'plan_snapshot',
    'input_image_hash',
    'result_json',
    'model_name',
    'prompt_version',
    'analysis_mode',
    'cache_key',
    'created_at',
    'updated_at'
  )
order by table_name, column_name;
